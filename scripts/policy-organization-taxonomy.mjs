export function sourceOwnerIndex(sourceRegistry = { sources: [] }) {
  return new Map((sourceRegistry.sources || []).map((source) => [source.name, source]));
}

export function normalizeDodOpr(opr) {
  const raw = String(opr || "").trim();
  const normalized = raw.toUpperCase().replace(/\s+/g, " ");
  const entities = [];
  const add = (id, code, name, tier = "departmental") => addEntity(entities, { id, code, name, tier, source: "dod_issuance_opr", raw_value: raw });

  if (/USW\(P&R\)/.test(normalized)) add("under-secretary-war-personnel-readiness", "USW(P&R)", "Under Secretary of War for Personnel and Readiness");
  if (/USW\(A&S\s*\)/.test(normalized) || /USW\(A&S\)/.test(normalized)) add("under-secretary-war-acquisition-sustainment", "USW(A&S)", "Under Secretary of War for Acquisition and Sustainment");
  if (/USW\(I&S\)/.test(normalized)) add("under-secretary-war-intelligence-security", "USW(I&S)", "Under Secretary of War for Intelligence and Security");
  if (/USW\(R&E\)/.test(normalized)) add("under-secretary-war-research-engineering", "USW(R&E)", "Under Secretary of War for Research and Engineering");
  if (/USW\(P\)(?!&)/.test(normalized)) add("under-secretary-war-policy", "USW(P)", "Under Secretary of War for Policy");
  if (/USW\(C\)/.test(normalized)) add("under-secretary-war-comptroller-cfo", "USW(C)/CFO", "Under Secretary of War Comptroller / Chief Financial Officer");
  if (/DOW?\s*CIO|DO W CIO/.test(normalized)) add("department-war-chief-information-officer", "DoW CIO", "Department of War Chief Information Officer");
  if (/\bGC\b/.test(normalized)) add("general-counsel-department-war", "GC DoW", "General Counsel of the Department of War");
  if (/\bIG\b/.test(normalized)) add("inspector-general-department-war", "IG DoW", "Inspector General of the Department of War");
  if (/DA&M/.test(normalized)) add("director-administration-management", "DA&M", "Director of Administration and Management");
  if (/ATSW\(PA\)/.test(normalized)) add("assistant-secretary-war-public-affairs", "ATSW(PA)", "Assistant to the Secretary of War for Public Affairs");
  if (/ASW\(SO\/LIC\)|ASW\(SOLIC\)/.test(normalized)) add("assistant-secretary-war-special-operations-low-intensity-conflict", "ASW(SO/LIC)", "Assistant Secretary of War for Special Operations and Low-Intensity Conflict");
  if (/ASW\(LA\)/.test(normalized)) add("assistant-secretary-war-legislative-affairs", "ASW(LA)", "Assistant Secretary of War for Legislative Affairs");
  if (/DOT&E/.test(normalized)) add("director-operational-test-evaluation", "DOT&E", "Director, Operational Test and Evaluation");
  if (/DCAPE/.test(normalized)) add("director-cost-assessment-program-evaluation", "DCAPE", "Director, Cost Assessment and Program Evaluation");
  if (/ES,\s*OSD/.test(normalized)) add("executive-secretary-office-secretary-war", "ES OSD", "Executive Secretary of the Office of the Secretary of War");
  if (/\bWHS\b/.test(normalized)) add("washington-headquarters-services", "WHS", "Washington Headquarters Services");

  if (entities.length) return entities;
  return [{
    id: slugFor(raw || "unknown-opr"),
    code: raw || null,
    name: raw || "Unknown OPR",
    tier: "departmental",
    source: "dod_issuance_opr_unmapped",
    raw_value: raw,
  }];
}

export function primaryResponsibleEntitiesFor(artifact, dodCatalogRow) {
  if (dodCatalogRow?.opr) return normalizeDodOpr(dodCatalogRow.opr);
  const fallback = artifact.issuing_organization || artifact.issuing_authority || "Unknown organization";
  return [{
    id: slugFor(fallback),
    code: null,
    name: fallback,
    tier: "source_owner",
    source: "artifact",
    raw_value: fallback,
  }];
}

export function organizationFacetsFor({ artifact, dodCatalogRow, sourceOwnerByName, primaryEntities = [] }) {
  const entities = [];
  for (const entity of primaryEntities) addEntity(entities, { ...entity, facet_source: entity.source || "responsible" });

  const sourceSystem = artifact.source_system || artifact.provenance?.source_system || "";
  const sourceRegistry = sourceOwnerByName?.get(sourceSystem) || null;
  if (sourceRegistry?.source_owner && !GENERIC_SOURCE_OWNERS.has(sourceRegistry.source_owner)) {
    addNamedEntity(entities, sourceRegistry.source_owner, {
      code: sourceRegistry.source_owner_code || null,
      tier: tierForSourceOwner(sourceRegistry.source_owner),
      source: "source_owner",
      raw_value: sourceSystem,
    });
  }

  const issuing = artifact.issuing_organization || "";
  if (issuing && !GENERIC_SOURCE_OWNERS.has(issuing)) {
    addNamedEntity(entities, issuing, {
      tier: tierForSourceOwner(issuing),
      source: "issuing_organization",
      raw_value: issuing,
    });
  }

  const sourceText = [
    artifact.id,
    artifact.title,
    artifact.short_title,
    artifact.artifact_type,
    artifact.family,
    artifact.jurisdiction,
    artifact.issuing_authority,
    artifact.issuing_organization,
    artifact.source_system,
    ...(artifact.tags || []),
    dodCatalogRow?.label,
    dodCatalogRow?.subject,
    dodCatalogRow?.opr,
  ].filter(Boolean).join(" ");

  for (const match of taxonomyMatches(sourceText)) {
    addEntity(entities, { ...match, source: "taxonomy_match", raw_value: sourceText.slice(0, 240) });
  }

  return entities;
}

function taxonomyMatches(text) {
  const normalized = normalizeForMatch(text);
  if (!normalized) return [];
  const matches = [];
  for (const entity of POLICY_ORGANIZATION_TAXONOMY) {
    if (entity.aliases.some((alias) => containsAlias(normalized, alias))) {
      matches.push({
        id: entity.id,
        code: entity.code,
        name: entity.name,
        tier: entity.tier,
      });
    }
  }
  return matches;
}

function containsAlias(normalizedText, alias) {
  const normalizedAlias = normalizeForMatch(alias);
  if (!normalizedAlias) return false;
  const escaped = normalizedAlias.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(^|[^A-Z0-9])${escaped}([^A-Z0-9]|$)`).test(normalizedText);
}

function addNamedEntity(entities, name, extra = {}) {
  const taxonomy = POLICY_ORGANIZATION_TAXONOMY.find((entity) => entity.name === name);
  addEntity(entities, {
    id: taxonomy?.id || slugFor(name),
    code: taxonomy?.code || extra.code || null,
    name: taxonomy?.name || name,
    tier: taxonomy?.tier || extra.tier || "source_owner",
    source: extra.source || "source_owner",
    raw_value: extra.raw_value || name,
  });
}

function addEntity(entities, entity) {
  if (!entity?.name) return;
  const taxonomy = POLICY_ORGANIZATION_TAXONOMY.find((candidate) => candidate.id === entity.id || candidate.name === entity.name);
  const id = taxonomy?.id || entity.id || slugFor(entity.name);
  const tier = taxonomy?.tier || entity.tier || "source_owner";
  const code = entity.code || taxonomy?.code || null;
  const existing = entities.find((candidate) => candidate.id === id);
  if (existing) {
    existing.code ||= code;
    if ((existing.tier === "source_owner" || existing.tier === "organization") && taxonomy?.tier) existing.tier = taxonomy.tier;
    return;
  }
  entities.push({
    id,
    code,
    name: taxonomy?.name || entity.name,
    tier,
    source: entity.source || entity.facet_source || "taxonomy",
    raw_value: entity.raw_value || entity.name,
  });
}

function tierForSourceOwner(name = "") {
  const value = String(name).toLowerCase();
  if (/army|navy|air force|space force|marine corps|coast guard/.test(value)) return "service";
  if (/command|navsea|navair|navwar|navfac|navsup|navcyberfor|military sealift|tradoc|afmc|cybercom|socom/.test(value)) return "command";
  if (/intelligence|security agency|reconnaissance|geospatial/.test(value)) return "intelligence_agency";
  if (/agency|office|chief digital|disa|cdao/.test(value)) return "defense_agency";
  return "component";
}

function normalizeForMatch(value) {
  return String(value || "")
    .toUpperCase()
    .replace(/&/g, " AND ")
    .replace(/[^A-Z0-9/]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function slugFor(value) {
  return String(value || "unknown")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 96) || "unknown";
}
